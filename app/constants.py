# app/constants.py
# Константы проекта QRKot.
# Собраны в одном месте, чтобы не дублировать значения в модулях
# и легко находить/менять их при необходимости.

# --- CharityProject ---

# Ограничения длины названия проекта.
MIN_LENGTH_PROJECT_NAME = 5
MAX_LENGTH_PROJECT_NAME = 100

# Минимальная длина описания проекта.
MIN_LENGTH_PROJECT_DESCRIPTION = 10

# --- User ---

# Максимальная длина email: ограничение из RFC 5321 (64 символа
# локальной части + 255 символов домена, итого 320 с разделителем).
MAX_LENGTH_USER_EMAIL = 320

# Максимальная длина хеша пароля с запасом под современные
# алгоритмы (bcrypt — 60 символов, argon2 — до ~100).
MAX_LENGTH_USER_PASSWORD_HASH = 128
